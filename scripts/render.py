#!/usr/bin/env python3
"""Render policy.yaml + shared/ + targets/ + bots/ into a dist tree.

Usage: python3 scripts/render.py [OUT_DIR]   (default: dist)
Output is deterministic (no timestamps beyond policy.yaml's `updated`), so
`make check` can diff a fresh render against the committed dist/.
"""
import json
import os
import re
import shutil
import sys
from string import Template

try:
    import yaml
except ImportError:
    sys.exit("render.py: PyYAML is required: python3 -m pip install --user pyyaml")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read()


def embed(md):
    """Drop the H1 and demote remaining headings one level for embedding."""
    lines = md.strip().splitlines()
    if lines and lines[0].startswith("# "):
        lines = lines[1:]
    out = [("#" + l) if re.match(r"^#{2,5} ", l) else l for l in lines]
    return "\n".join(out).strip()


def rules_md(policy):
    return "\n".join(
        f"- `{r['id']}` {r['title']}. {r['text']} (enforced by: {', '.join(r['enforced_by'])})"
        for r in policy["rules"])


def layout_md(policy):
    rows = ["| Path | Owner | Purpose |", "| --- | --- | --- |"]
    root = policy["workspace"]["root"]
    for e in policy["workspace"]["layout"]:
        rows.append(f"| `{root}/{e['path']}` | `{e['owner']}` | {e['purpose']} |")
    return "\n".join(rows)


def limits_md(policy):
    return "\n".join(f"- `{l['name']}`: {l['value']} ({l['kind']})" for l in policy["limits"])


ENFORCERS = {"convention", "auto-review", "hook"}
HOOK_KEYS = ("id", "intent", "action", "secret_names", "gh_write", "root", "protected_dirs")


def validate(policy):
    """Fail the render if a rule claims an enforcement mechanism that does not exist."""
    for r in policy["rules"]:
        bad = set(r["enforced_by"]) - ENFORCERS
        if bad:
            sys.exit(f"render.py: {r['id']} claims enforced_by {sorted(bad)}, which no mechanism provides")


def load_policy():
    """policy.yaml, plus Git-ignored policy.local.yaml for environment-specific values."""
    policy = yaml.safe_load(read("policy.yaml"))
    local = os.path.join(ROOT, "policy.local.yaml")
    if os.environ.get("AGENT_POLICIES_LOCAL") == "1" and os.path.isfile(local):
        with open(local, encoding="utf-8") as f:
            extra = yaml.safe_load(f) or {}
        for h in policy["hooks"]:
            h.setdefault("secret_names", [])
            h["secret_names"] += extra.get("secret_names", {}).get(h["id"], [])
    return policy


def auto_review_md(policy):
    parts = []
    for h in policy["hooks"]:
        if h.get("grok-bot") != "auto-review":
            continue
        parts.append(f"## {h['id']}\n\n- Rule: {h['intent']}\n- Action: {h['action']}")
    for r in policy["rules"]:
        if "auto-review" in r["enforced_by"]:
            parts.append(f"## {r['id']}\n\n- Rule: {r['title']}. {r['text']}\n- Action: ask")
    return "\n\n".join(parts)


def main():
    out = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "dist"))
    policy = load_policy()
    validate(policy)
    v = str(policy["version"])
    external = [s for s in policy["skills"] if "install" in s]
    ctx = {
        "version": v,
        "header": f"<!-- Generated by agent-policies {v} from policy.yaml. Do not edit; run make render. -->",
        "rules": rules_md(policy),
        "layout": layout_md(policy),
        "limits": limits_md(policy),
        "auto_review": auto_review_md(policy),
        "principles": embed(read("shared/principles.md")),
        "practices": embed(read("shared/best-practices.md")),
        "skills_md": "\n\n".join(
            f"### {s['name']}\n\nSource `{s['source']}`, path `{s.get('path', '.')}`, version `{s['version']}`.\n\n"
            f"```bash\n{s['install']}\n```" for s in external),
        "skills_sh": "\n".join(f"#   {s['install']}  # {s['name']} {s['version']}" for s in external),
    }

    if os.path.isdir(out):
        shutil.rmtree(out)
    files = {}

    def tmpl(src, dst):
        files[dst] = Template(read(src)).substitute(ctx).strip() + "\n"

    tmpl("targets/grok-bot/SKILL.md.tmpl", "grok-bot/workspace-conventions/SKILL.md")
    tmpl("targets/grok-bot/auto-review-rules.md.tmpl", "grok-bot/auto-review-rules.md")
    tmpl("targets/cursor/agent-policies.mdc.tmpl", "cursor/.cursor/rules/agent-policies.mdc")
    tmpl("targets/cursor/AGENTS.md.tmpl", "cursor/AGENTS.md")
    tmpl("targets/cursor/install.sh.tmpl", "cursor/.cursor/install.sh")
    tmpl("targets/grok-build/AGENTS.md.tmpl", "grok-build/AGENTS.md")
    tmpl("targets/INSTALL.md.tmpl", "INSTALL.md")
    files["cursor/.cursor/hooks/guard-shell.py"] = read("targets/cursor/guard-shell.py")

    cursor_hooks = [h for h in policy["hooks"] if h.get("cursor") == "beforeShellExecution"]
    files["cursor/.cursor/hooks/policy-hooks.json"] = json.dumps({
        "version": v,
        "hooks": [{k: h[k] for k in HOOK_KEYS if k in h} for h in cursor_hooks],
    }, indent=2) + "\n"
    files["cursor/.cursor/hooks.json"] = json.dumps({
        "version": 1,
        "hooks": {"beforeShellExecution": [
            {"command": "python3 .cursor/hooks/guard-shell.py", "failClosed": True}]},
    }, indent=2) + "\n"
    files["cursor/.cursor/environment.json"] = json.dumps(
        {"install": "bash .cursor/install.sh"}, indent=2) + "\n"
    files["VERSION"] = v + "\n"

    bots_dir = os.path.join(ROOT, "bots")
    for bot in sorted(os.listdir(bots_dir)):
        src = os.path.join("bots", bot, "AGENTS.md")
        if bot.startswith("_") or not os.path.isfile(os.path.join(ROOT, src)):
            continue
        files[f"bots/{bot}/AGENTS.md"] = (
            ctx["header"] + "\n\n" + read(src).strip()
            + f"\n\n## Shared rules (agent-policies {v})\n\n" + ctx["rules"] + "\n")

    executable = {"cursor/.cursor/install.sh", "cursor/.cursor/hooks/guard-shell.py"}
    for rel, text in sorted(files.items()):
        path = os.path.join(out, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        tmp = path + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(text)
        os.chmod(tmp, 0o755 if rel in executable else 0o644)
        os.replace(tmp, path)  # atomic rename (ATOM-1)
    print(f"rendered {len(files)} files for agent-policies {v} into {os.path.relpath(out, ROOT)}")


if __name__ == "__main__":
    main()
